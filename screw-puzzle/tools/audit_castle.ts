import { writeFileSync } from "node:fs";
import { createCastleModel } from "../src/scene/castleModel.ts";
import { registerModel } from "../src/scene/levelModels.ts";
import { SCREW_SCALE } from "../src/game/screwScale.ts";
import { SCREW_COLOR_ORDER } from "../src/game/types.ts";
import { createInitialState } from "../src/game/rules.ts";
import { findScrewObstructions } from "../src/scene/obstructions.ts";
import { findExposedScrews } from "../src/scene/exposure.ts";
const built = createCastleModel();
registerModel("castle", built.model);
const screws = built.mounts.map((mount, i) => ({
  ...mount,
  id: `castle-${i + 1}`,
  removed: false,
  color: SCREW_COLOR_ORDER[Math.floor(i / 3) % 12],
  obstructedBy: findScrewObstructions(mount, SCREW_SCALE),
}));
const exposed = findExposedScrews(createInitialState(screws), "castle");
const remaining = new Set(built.model.parts),
  done = new Set<string>();
for (let pass = 0; pass < 300; pass++) {
  const ready = [...remaining].filter((part) =>
    screws
      .filter((s) => s.attachedTo === part)
      .every((s) =>
        [...s.obstructedBy, ...(s.solutionAfter ?? [])].every((p) =>
          done.has(p),
        ),
      ),
  );
  if (!ready.length) break;
  for (const part of ready) {
    remaining.delete(part);
    done.add(part);
  }
}
writeFileSync(
  new URL("../src/scene/castleAudit.ts", import.meta.url),
  `// Generated by node tools/audit_castle.ts. Do not edit by hand.\nimport type { CastlePartId } from "../game/types.ts";\nexport const CASTLE_BLOCKERS: readonly (readonly CastlePartId[])[] = ${JSON.stringify(
    screws.map((s) => s.obstructedBy),
    null,
    2,
  )};\nexport const CASTLE_EXPOSED_IDS = ${JSON.stringify(exposed)} as const;\n`,
);
console.log(
  JSON.stringify({
    screws: screws.length,
    owners: built.model.parts.length,
    pieces: built.model.pieces.length,
    exposed: exposed.length,
    stuck: remaining.size,
  }),
);
if (remaining.size)
  console.log(
    JSON.stringify(
      screws
        .filter((s) => remaining.has(s.attachedTo))
        .map((s) => ({
          id: s.id,
          part: s.attachedTo,
          position: s.position,
          needs: [...s.obstructedBy, ...(s.solutionAfter ?? [])].filter(
            (p) => !done.has(p),
          ),
        })),
      null,
      2,
    ),
  );
