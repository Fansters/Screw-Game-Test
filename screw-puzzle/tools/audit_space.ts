import "../src/game/allLevels.ts";
// Rebuild after editing Moonbase Odyssey geometry or screw mounts.
import { writeFileSync } from "node:fs";
import { SPACE_MOUNTS } from "../src/game/allLevels.ts";
import { SCREW_SCALE } from "../src/game/allLevels.ts";
import { SCREW_COLOR_ORDER } from "../src/game/types.ts";
import { createInitialState } from "../src/game/rules.ts";
import { findScrewObstructions } from "../src/scene/obstructions.ts";
import { findExposedScrews } from "../src/scene/exposure.ts";
const screws = SPACE_MOUNTS.map((mount, index) => ({ ...mount, id: `space-${index + 1}`, removed: false,
  color: SCREW_COLOR_ORDER[Math.floor(index / 3) % SCREW_COLOR_ORDER.length], obstructedBy: findScrewObstructions(mount, SCREW_SCALE) }));
const exposed = findExposedScrews(createInitialState(screws), "space");
writeFileSync(new URL("../src/scene/spaceAudit.ts", import.meta.url),
  '// Generated by node tools/audit_space.ts. Do not edit by hand.\nimport type { SpacePartId } from "../game/types.ts";\n' +
  `export const SPACE_BLOCKERS: readonly (readonly SpacePartId[])[] = ${JSON.stringify(screws.map(s => s.obstructedBy), null, 2)};\n` +
  `export const SPACE_EXPOSED_IDS = ${JSON.stringify(exposed)} as const;\n`);
console.log(`${screws.length} screws; ${exposed.length} initially exposed across 80 views.`);
