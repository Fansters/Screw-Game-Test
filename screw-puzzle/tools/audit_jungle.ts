import { writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { createJungleModel } from '../src/scene/jungleModel.ts';
import { registerModel } from '../src/scene/levelModels.ts';
import { findScrewObstructions } from '../src/scene/obstructions.ts';
import { findExposedScrews } from '../src/scene/exposure.ts';
import { createInitialState } from '../src/game/rules.ts';
import { EASY_PROFILE } from '../src/game/difficultyProfiles.ts';
import { SCREW_SCALE } from '../src/game/screwScale.ts';
import type { PartId, Screw } from '../src/game/types.ts';

const built = createJungleModel();
registerModel('jungle', built.model);
const screws: Screw[] = built.mounts.map((mount, i) => ({
  ...mount, id: `jungle-${i + 1}`, removed: false,
  color: EASY_PROFILE.colors[Math.floor(i / 3) % EASY_PROFILE.colors.length],
  obstructedBy: findScrewObstructions(mount, SCREW_SCALE),
}));
const remaining = new Set<PartId>(built.model.parts), depths = new Map<PartId, number>();
while (remaining.size) {
  const ready = [...remaining].filter(part => screws.filter(s => s.attachedTo === part)
    .every(s => s.obstructedBy!.every(cover => depths.has(cover))));
  // Never overwrite a valid cache with a circular, unplayable assembly plan.
  assert.ok(ready.length, `Jungle cover cycle: ${[...remaining].join(', ')}`);
  for (const part of ready) {
    depths.set(part, Math.max(0, ...screws.filter(s => s.attachedTo === part)
      .flatMap(s => s.obstructedBy!.map(cover => depths.get(cover)! + 1))));
    remaining.delete(part);
  }
}
const exposed = findExposedScrews(createInitialState(screws), 'jungle');
const triangles = built.model.pieces.reduce((sum, p) => sum + (p.geometry!.index?.count ?? p.geometry!.attributes.position.count) / 3, 0);
const report = {
  level: 'jungle', difficulty: 'easy', screws: screws.length, owners: built.model.parts.length,
  pieces: built.model.pieces.length, sceneryTriangles: triangles,
  palette: EASY_PROFILE.colors,
  initiallyClearExtraction: screws.filter(s => !s.obstructedBy!.length).length,
  orbitSampledVisible: exposed.length,
  orbitSampledVisiblePercent: Number((100 * exposed.length / screws.length).toFixed(2)),
  coverDepthCounts: Object.fromEntries([...new Set(depths.values())].sort((a,b) => a-b)
    .map(depth => [depth, [...depths.values()].filter(value => value === depth).length])),
  maxCoverDepth: Math.max(...depths.values()),
  openingTargetMet: exposed.length >= Math.round(EASY_PROFILE.openingExposure[0] * screws.length) && exposed.length <= Math.round(EASY_PROFILE.openingExposure[1] * screws.length),
  notes: 'Depth counts describe physical extraction chains, including buried foundations. Visibility is sampled across orbit views, not one screenshot. Run tests/jungle.test.ts separately for full winning routes, actual viewing paths, spacing, attachment and physics.',
};
assert.ok(screws.length >= EASY_PROFILE.screwBudget[0] && screws.length <= EASY_PROFILE.screwBudget[1]);
// Exposure is an authoring target. Never retain a false blocker to meet a quota.
if (!report.openingTargetMet) console.warn('Opening is outside the approximate Easy target; physically clear screws remain playable.');
assert.ok(triangles >= 250000 && triangles <= 350000);
writeFileSync(new URL('../src/scene/jungleAudit.ts', import.meta.url),
  `// Generated by node tools/audit_jungle.ts. Do not edit by hand.\nimport type {JunglePartId} from '../game/types.ts';\nexport const JUNGLE_BLOCKERS:readonly(readonly JunglePartId[])[]=${JSON.stringify(screws.map(s => s.obstructedBy), null, 1)};\nexport const JUNGLE_EXPOSED_IDS=${JSON.stringify(exposed)} as const;\n`);
writeFileSync(new URL('../docs/jungle-difficulty.json', import.meta.url), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report));
