import "../src/game/allLevels.ts";
// Rebuild after changing construction geometry or screw placements.
import { writeFileSync } from "node:fs";
import { CONSTRUCTION_MOUNTS } from "../src/game/allLevels.ts";
import { SCREW_SCALE } from "../src/game/allLevels.ts";
import { SCREW_COLOR_ORDER } from "../src/game/types.ts";
import { createInitialState } from "../src/game/rules.ts";
import { findScrewObstructions } from "../src/scene/obstructions.ts";
import { findExposedScrews } from "../src/scene/exposure.ts";
const screws = CONSTRUCTION_MOUNTS.map((mount, index) => ({
  ...mount,
  id: `construction-${index + 1}`,
  removed: false,
  color: SCREW_COLOR_ORDER[Math.floor(index / 3) % SCREW_COLOR_ORDER.length],
  obstructedBy: findScrewObstructions(mount, SCREW_SCALE),
}));
const exposed = findExposedScrews(createInitialState(screws), "construction");
const source =
  `// Generated by node tools/audit_construction.ts. Do not edit by hand.\n` +
  `import type { ConstructionPartId } from "../game/types.ts";\n` +
  `export const CONSTRUCTION_BLOCKERS: readonly (readonly ConstructionPartId[])[] = ${JSON.stringify(
    screws.map((s) => s.obstructedBy),
    null,
    2,
  )};\n` +
  `export const CONSTRUCTION_EXPOSED_IDS = ${JSON.stringify(exposed)} as const;\n`;
writeFileSync(
  new URL("../src/scene/constructionAudit.ts", import.meta.url),
  source,
);
console.log(
  `${screws.length} screws; ${exposed.length} initially exposed across 80 views.`,
);
