// Rebuild after changing carnival geometry or screw placements.
import { writeFileSync } from "node:fs";
import { CARNIVAL_MOUNTS } from "../src/scene/carnivalModel.ts";
import { SCREW_SCALE } from "../src/game/levels.ts";
import { SCREW_COLOR_ORDER } from "../src/game/types.ts";
import { createInitialState } from "../src/game/rules.ts";
import { findScrewObstructions } from "../src/scene/obstructions.ts";
import { findExposedScrews } from "../src/scene/exposure.ts";
const screws = CARNIVAL_MOUNTS.map((mount, index) => ({
  ...mount,
  id: `carnival-${index + 1}`,
  removed: false,
  color: SCREW_COLOR_ORDER[Math.floor(index / 3) % SCREW_COLOR_ORDER.length],
  obstructedBy: findScrewObstructions(mount, SCREW_SCALE),
}));
const exposed = findExposedScrews(createInitialState(screws), "carnival");
const source =
  `// Generated by node tools/audit_carnival.ts. Do not edit by hand.\n` +
  `import type { CarnivalPartId } from "../game/types.ts";\n` +
  `export const CARNIVAL_BLOCKERS: readonly (readonly CarnivalPartId[])[] = ${JSON.stringify(
    screws.map((s) => s.obstructedBy),
    null,
    2,
  )};\n` +
  `export const CARNIVAL_EXPOSED_IDS = ${JSON.stringify(exposed)} as const;\n`;
writeFileSync(
  new URL("../src/scene/carnivalAudit.ts", import.meta.url),
  source,
);
console.log(
  `${screws.length} screws; ${exposed.length} initially exposed across 80 views.`,
);
