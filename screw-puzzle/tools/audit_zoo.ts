// Rebuild after changing zoo geometry or screw placements.
import { writeFileSync } from "node:fs";
import { ZOO_MOUNTS } from "../src/scene/zooModel.ts";
import { SCREW_SCALE } from "../src/game/levels.ts";
import { SCREW_COLOR_ORDER } from "../src/game/types.ts";
import { createInitialState } from "../src/game/rules.ts";
import { findScrewObstructions } from "../src/scene/obstructions.ts";
import { findExposedScrews } from "../src/scene/exposure.ts";
const screws = ZOO_MOUNTS.map((mount, index) => ({
  ...mount,
  id: `zoo-${index + 1}`,
  removed: false,
  color: SCREW_COLOR_ORDER[Math.floor(index / 3) % SCREW_COLOR_ORDER.length],
  obstructedBy: findScrewObstructions(mount, SCREW_SCALE),
}));
const exposed = findExposedScrews(createInitialState(screws), "zoo");
const source =
  `// Generated by node tools/audit_zoo.ts. Do not edit by hand.\n` +
  `import type { ZooPartId } from "../game/types.ts";\n` +
  `export const ZOO_BLOCKERS: readonly (readonly ZooPartId[])[] = ${JSON.stringify(
    screws.map((s) => s.obstructedBy),
    null,
    2,
  )};\n` +
  `export const ZOO_EXPOSED_IDS = ${JSON.stringify(exposed)} as const;\n`;
writeFileSync(new URL("../src/scene/zooAudit.ts", import.meta.url), source);
console.log(
  `${screws.length} screws; ${exposed.length} initially exposed across 80 views.`,
);
