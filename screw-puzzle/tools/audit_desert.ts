// Rebuild after changing Route 66 geometry or screw placements.
// The game loads these static results; tests independently check the meshes.
import { writeFileSync } from "node:fs";
import { DESERT_MOUNTS } from "../src/scene/desertModel.ts";
import { SCREW_SCALE } from "../src/game/levels.ts";
import { SCREW_COLOR_ORDER } from "../src/game/types.ts";
import { createInitialState } from "../src/game/rules.ts";
import { findScrewObstructions } from "../src/scene/obstructions.ts";
import { findExposedScrews } from "../src/scene/exposure.ts";
const screws = DESERT_MOUNTS.map((mount, index) => ({ ...mount, id: `desert-${index + 1}`, removed: false,
  color: SCREW_COLOR_ORDER[Math.floor(index / 3) % SCREW_COLOR_ORDER.length],
  obstructedBy: findScrewObstructions(mount, SCREW_SCALE),
}));
const exposed = findExposedScrews(createInitialState(screws), "desert");
const source = `// Generated by node tools/audit_desert.ts. Do not edit by hand.\n` +
  `import type { DesertPartId } from "../game/types.ts";\n` +
  `export const DESERT_BLOCKERS: readonly (readonly DesertPartId[])[] = ${JSON.stringify(screws.map(s => s.obstructedBy), null, 2)};\n` +
  `export const DESERT_EXPOSED_IDS = ${JSON.stringify(exposed)} as const;\n`;
writeFileSync(new URL("../src/scene/desertAudit.ts", import.meta.url), source);
console.log(`${screws.length} screws; ${exposed.length} initially exposed across 80 views.`);
